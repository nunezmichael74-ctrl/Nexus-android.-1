window.pickLang = function (stored) {
  const L = window.I18N;
  if (stored && L[stored]) return stored;
  for (const l of navigator.languages || [navigator.language || 'es']) {
    const k = String(l).toLowerCase().split('-')[0];
    if (L[k]) return k;
  }
  return 'en';
};
